import type { DuesFrequency, DuesPayment, DuesSummary, User } from "./models";

export const DUES_TIME_ZONE = "America/New_York";
export const MONTHLY_DUES_CENTS = 2000;
export const ANNUAL_DUES_CENTS = MONTHLY_DUES_CENTS * 12;
export const SEMIANNUAL_DUES_CENTS = MONTHLY_DUES_CENTS * 6;
export const DUES_PLAN_LABELS: Record<DuesFrequency, string> = {
  yearly: "Yearly", monthly: "Monthly", "twice-yearly": "Twice yearly",
};
export function isDuesFrequency(value: unknown): value is DuesFrequency {
  return value === "yearly" || value === "monthly" || value === "twice-yearly";
}
export function clubDate(now = new Date()): string {
  return new Intl.DateTimeFormat("en-CA", { timeZone: DUES_TIME_ZONE, year: "numeric", month: "2-digit", day: "2-digit" }).format(now);
}
function monthIndex(date: string): number {
  return Number(date.slice(0, 4)) * 12 + Number(date.slice(5, 7)) - 1;
}
function monthDate(month: number, day = 1): string {
  return `${Math.floor(month / 12)}-${String(month % 12 + 1).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
}
function monthEnd(month: number): string {
  return new Date(Date.UTC(Math.floor(month / 12), month % 12 + 1, 0)).toISOString().slice(0, 10);
}
function slotDate(slot: number): string { return monthDate(Math.floor(slot / 2), slot % 2 ? 16 : 1); }
function slotEnd(slot: number): string { return slot % 2 ? monthEnd(Math.floor(slot / 2)) : monthDate(Math.floor(slot / 2), 15); }
function dateSlot(date: string): number { return monthIndex(date) * 2 + (Number(date.slice(8, 10)) >= 16 ? 1 : 0); }
// Half-month accounting units preserve historical partial payments. New plans
// cover 12 months ($240), six months ($120), or one month ($20).
export function slotCents(slot: number): number {
  const position = ((slot % 24) + 24) % 24;
  return Math.floor((position + 1) * ANNUAL_DUES_CENTS / 24) - Math.floor(position * ANNUAL_DUES_CENTS / 24);
}
function quote(start: number, count: number) {
  let amountCents = 0;
  for (let slot = start; slot < start + count; slot++) amountCents += slotCents(slot);
  return { amountCents, coverageStart: slotDate(start), coverageEnd: slotEnd(start + count - 1) };
}

/** Recognize only the exact four-row batch generated by the retired GET handler.
 * A real payment that replaced a seeded pending row is always preserved. */
export function splitDuesPlaceholders(records: DuesPayment[]) {
  const fakeIds = new Set<string>();
  const groups = new Map<string, DuesPayment[]>();
  for (const record of records) {
    if (record.schemaVersion) continue;
    const key = `${record.userId}:${record.createdAt}`;
    const group = groups.get(key) ?? [];
    group.push(record);
    groups.set(key, group);
  }
  for (const group of groups.values()) {
    const fakePaid = group.filter(r => r.status === "paid" && r.paymentMethod === "bank-transfer" &&
      /^ECP-PAY-[A-Z0-9]{8}$/.test(r.reference ?? "") && r.paidDate === `${r.year}-02-15` &&
      r.dueDate === `${r.year}-03-31` && (r.amount === 20 || r.amount === 5000));
    const years = fakePaid.map(r => r.year).sort((a, b) => a - b);
    if (years.length !== 3 || years[2] - years[0] !== 2) continue;
    fakePaid.forEach(r => fakeIds.add(r.id));
    group.filter(r => r.year === years[2] + 1 && r.status === "pending" && !r.reference && !r.zelleRef && !r.paypalOrderId && !r.paystackRef && !r.paidDate && r.dueDate === `${r.year}-03-31`).forEach(r => fakeIds.add(r.id));
  }
  return { records: records.filter(r => !fakeIds.has(r.id)), placeholders: records.filter(r => fakeIds.has(r.id)) };
}

export function calculateDues(user: Pick<User, "joinedAt" | "membershipIdIssuedAt" | "duesStartDate" | "duesFrequency">, input: DuesPayment[], now = new Date()): DuesSummary {
  const { records } = splitDuesPlaceholders(input);
  const today = clubDate(now);
  const currentMonth = monthIndex(today);
  const baseline = user.duesStartDate ?? monthDate(monthIndex(clubDate(new Date(user.membershipIdIssuedAt ?? user.joinedAt))) + 1);
  const startSlot = dateSlot(baseline);
  // Interpret any saved preference from the superseded plan as twice yearly;
  // previously recorded payment amounts and coverage remain authoritative.
  const savedFrequency: unknown = user.duesFrequency;
  const frequency: DuesFrequency = isDuesFrequency(savedFrequency) ? savedFrequency : savedFrequency === "twice-monthly" ? "twice-yearly" : "monthly";
  const covered = new Set<number>();
  for (const payment of records) {
    if (payment.status !== "paid" && payment.status !== "waived") continue;
    const first = payment.coverageStart ? dateSlot(payment.coverageStart) : payment.year * 24;
    const last = payment.coverageEnd ? dateSlot(payment.coverageEnd) : payment.year * 24 + 23;
    for (let slot = first; slot <= last; slot++) covered.add(slot);
  }
  let firstUnpaid = startSlot;
  while (covered.has(firstUnpaid)) firstUnpaid++;
  const lastDueSlot = currentMonth * 2 + 1;
  let outstandingCents = 0;
  const owed = new Set<string>();
  const completedOwed = new Set<string>();
  for (let slot = startSlot; slot <= lastDueSlot; slot++) {
    if (covered.has(slot)) continue;
    outstandingCents += slotCents(slot);
    const month = Math.floor(slot / 2);
    owed.add(monthDate(month).slice(0, 7));
    if (month < currentMonth || today === monthEnd(currentMonth)) completedOwed.add(monthDate(month).slice(0, 7));
  }
  const suspensionWarning = completedOwed.size >= 3;
  const plans = (["yearly", "monthly", "twice-yearly"] as const).map(plan => {
    const count = plan === "yearly" ? 24 : plan === "twice-yearly" ? 12 : 2;
    // Do not charge again for previously covered slots within a quote.
    let end = firstUnpaid;
    while (end + 1 < firstUnpaid + count && !covered.has(end + 1)) end++;
    return { frequency: plan, ...quote(firstUnpaid, end - firstUnpaid + 1) };
  });
  // Catch-up may contain gaps from legacy annual payments; count only unpaid slots.
  const contiguousCatchUpEnd = (() => {
    let end = firstUnpaid;
    while (end <= lastDueSlot && !covered.has(end)) end++;
    return end - 1;
  })();
  return {
    frequency, billingStartsOn: baseline, asOf: today,
    status: suspensionWarning ? "at-risk" : outstandingCents > 0 ? "owing" : "current",
    overdueMonths: [...owed], outstandingCents,
    paidThrough: firstUnpaid > startSlot ? slotEnd(firstUnpaid - 1) : null,
    nextPaymentDue: slotDate(firstUnpaid), suspensionWarning,
    totalPaidCents: records.filter(r => r.status === "paid").reduce((sum, r) => sum + Math.round(r.amount * 100), 0),
    pendingPayment: records.find(r => r.schemaVersion === 2 && r.status === "pending") ?? null,
    plans,
    catchUp: contiguousCatchUpEnd >= firstUnpaid ? quote(firstUnpaid, contiguousCatchUpEnd - firstUnpaid + 1) : null,
  };
}
